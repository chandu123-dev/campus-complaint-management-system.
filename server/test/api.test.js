import http from 'http';
import app from '../app.js';

let server;
const PORT = 5432;
const BASE = `http://localhost:${PORT}/api`;

async function request(path, options = {}) {
  const url = `${BASE}${path}`;
  const res = await fetch(url, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...options.headers
    }
  });
  const data = await res.json();
  return { status: res.status, data };
}

async function runTests() {
  console.log('🧪 Starting Campus Complaint Management System API Automated Tests...\n');
  server = http.createServer(app);
  await new Promise(resolve => server.listen(PORT, resolve));

  let passed = 0;
  let failed = 0;

  function assert(condition, name) {
    if (condition) {
      console.log(`  ✅ PASS: ${name}`);
      passed++;
    } else {
      console.error(`  ❌ FAIL: ${name}`);
      failed++;
    }
  }

  try {
    // 1. Health check
    const health = await request('/health');
    assert(health.status === 200 && health.data.status === 'ok', 'GET /api/health returns 200 OK');

    // 2. Student Login
    const stuLogin = await request('/auth/login', {
      method: 'POST',
      body: JSON.stringify({ identifier: 'STU2024042', password: 'StudentPassword123!' })
    });
    assert(stuLogin.status === 200 && stuLogin.data.success && !!stuLogin.data.token, 'POST /api/auth/login works for verified student');
    const studentToken = stuLogin.data.token;

    // 3. Admin Login
    const admLogin = await request('/auth/login', {
      method: 'POST',
      body: JSON.stringify({ identifier: 'admin@campus.edu', password: 'AdminPassword123!' })
    });
    assert(admLogin.status === 200 && admLogin.data.user.role === 'admin', 'POST /api/auth/login works for administrator');
    const adminToken = admLogin.data.token;

    // 4. Student profile retrieval
    const me = await request('/auth/me', {
      headers: { Authorization: `Bearer ${studentToken}` }
    });
    assert(me.status === 200 && me.data.user.studentId === 'STU2024042', 'GET /api/auth/me returns current authenticated student');

    // 5. Submit complaint
    const newComplaint = await request('/complaints', {
      method: 'POST',
      headers: { Authorization: `Bearer ${studentToken}` },
      body: JSON.stringify({
        title: 'Automated Test: Flickering LED strip in CS Reading Hall',
        description: 'Test description generated by automated test suite.',
        category: 'Electrical',
        location: 'The Nexus Central Library',
        priority: 'High'
      })
    });
    assert(newComplaint.status === 201 && newComplaint.data.success && newComplaint.data.complaint.status === 'Submitted', 'POST /api/complaints creates valid complaint with unique ID');
    const createdId = newComplaint.data.complaint._id;

    // 6. Admin Triage & Status Update
    const statusUpdate = await request(`/complaints/${createdId}/status`, {
      method: 'PATCH',
      headers: { Authorization: `Bearer ${adminToken}` },
      body: JSON.stringify({
        status: 'Acknowledged',
        remarks: 'Test suite supervisor review'
      })
    });
    assert(statusUpdate.status === 200 && statusUpdate.data.complaint.status === 'Acknowledged', 'PATCH /api/complaints/:id/status updates lifecycle and history');

    // 7. Admin Dashboard statistics
    const dash = await request('/admin/dashboard', {
      headers: { Authorization: `Bearer ${adminToken}` }
    });
    assert(dash.status === 200 && dash.data.stats.totalComplaints > 0, 'GET /api/admin/dashboard compiles live DB statistics');

    // 8. Categories endpoint
    const cats = await request('/categories');
    assert(cats.status === 200 && Array.isArray(cats.data.categories) && cats.data.categories.length > 0, 'GET /api/categories returns active taxonomy');

    console.log(`\n📊 Test Run Completed: ${passed} Passed, ${failed} Failed.`);
  } catch (err) {
    console.error('Fatal test runner error:', err);
  } finally {
    server.close();
    process.exit(failed > 0 ? 1 : 0);
  }
}

runTests();
